"""Deterministic financial and market forecast calculator for Project Atlas.

CRITICAL REQUIREMENT:
Forecast and CAGR calculations must be performed by a deterministic calculator,
never mental arithmetic generated by an LLM.
"""

import math
from typing import Any, Dict, List, Optional


def calculate_cagr(
    beginning_value: float,
    ending_value: float,
    num_years: float,
    base_year: Optional[int] = None,
    end_year: Optional[int] = None,
    unit: str = "USD Billion",
) -> Dict[str, Any]:
    """Calculate Compound Annual Growth Rate (CAGR).

    Formula: CAGR = (Ending Value / Beginning Value)^(1 / Number of Years) - 1
    """
    if beginning_value <= 0:
        raise ValueError("Beginning value must be greater than zero.")
    if ending_value <= 0:
        raise ValueError("Ending value must be greater than zero.")
    if num_years <= 0:
        raise ValueError("Number of years must be greater than zero.")

    cagr_decimal = math.pow((ending_value / beginning_value), (1.0 / num_years)) - 1.0
    cagr_percent = round(cagr_decimal * 100, 2)

    formula_str = "CAGR = (Ending Value / Beginning Value)^(1 / Number of Years) - 1"
    assumptions = [
        "Constant currency valuation",
        f"Forecast period: {base_year or 'Base Year'} to {end_year or 'Target Year'} ({num_years} years)",
    ]

    return {
        "metric_name": "CAGR",
        "formula": formula_str,
        "inputs": {
            "beginning_value": beginning_value,
            "ending_value": ending_value,
            "years": num_years,
            "base_year": base_year,
            "end_year": end_year,
            "unit": unit,
        },
        "assumptions": assumptions,
        "result": f"{cagr_percent}%",
        "raw_value": cagr_percent,
    }


def calculate_projection(
    base_value: float,
    cagr_percent: float,
    num_years: float,
    base_year: int,
    target_year: int,
    unit: str = "USD Billion",
    caveats: Optional[List[str]] = None,
) -> Dict[str, Any]:
    """Calculate future market valuation from CAGR.

    Formula: Future Value = Base Value * (1 + CAGR/100)^Years
    """
    if base_value <= 0:
        raise ValueError("Base value must be greater than zero.")
    if num_years <= 0:
        num_years = target_year - base_year
    if num_years <= 0:
        raise ValueError("Target year must be greater than base year.")

    rate = cagr_percent / 100.0
    projected_value = base_value * math.pow((1.0 + rate), num_years)
    rounded_value = round(projected_value, 2)

    formula_str = f"Future Value = Base Value * (1 + CAGR)^{int(num_years)}"
    assumptions = [
        f"Base year established as {base_year} (value: {base_value} {unit})",
        f"Annual compound growth rate applied: {cagr_percent}%",
        f"Target forecast horizon: {target_year} ({int(num_years)} compounding periods)",
    ]
    if caveats:
        assumptions.extend(caveats)

    return {
        "metric_name": f"{target_year} Projected Valuation",
        "formula": formula_str,
        "inputs": {
            "base_value": base_value,
            "cagr_percent": cagr_percent,
            "base_year": base_year,
            "target_year": target_year,
            "years": num_years,
            "unit": unit,
        },
        "assumptions": assumptions,
        "result": f"{rounded_value} {unit}",
        "raw_value": rounded_value,
    }
